// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other pre-token protocol the snapshot can rank: the early rows the radar exists to find. A protocol
// is pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// What radar-2 changes against the starter's radar-1, and why:
//
// 1. The board no longer ranks wrapped, staked or bridged products. The starter ranked any pre-token
//    protocol by TVL, so its top rows were wrapped Bitcoin, staked ETH and bridge contracts --
//    products of tokens that already trade, which will never launch a token of their own. radar-2
//    applies the watchlist's own exclusion rule to every row (Bridge / Canonical Bridge / Liquid
//    Staking / Liquid Restaking / Restaked BTC / CEX categories, wrapped / staked / staking in the
//    name, an exchange's name at the start, a version marker), from the snapshot's own fields.
//    144 pre-token protocols are set aside by it; 198 rankable rows remain, watchlist included.
//
// 2. The value multiple is measured, not assumed. radar-1 multiplied every TVL by 0.25. radar-2
//    measures the market's own multiple from this snapshot's live-token protocols: the median
//    market-cap-to-TVL ratio, per category where at least four live peers exist, shrunk toward the
//    global median (prior weight 8) and clamped to [0.05, 0.80]. A category with too few live peers
//    falls back to the global median, so one outlier cannot set a multiple. No protocol name is
//    ever special-cased: the same function scores every row.
//
// Implied value follows only from the snapshot's own figures:
//
//   categoryMultiple = shrunk median(mcap_usd / tvl_usd) of the live peers, or the global median
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.45
//   maturity   = 0.60 + min(age_days, 1095) / 1095 x 0.40   (age_days unknown: 365)
//   breadth    = 1 + 0.02 x min(chains - 1, 5)              (more chains, more reach)
//   implied    = max(1, round(tvl_usd x categoryMultiple x growthMult x maturity x breadth))
//
// The constants are stated in the dashboard and changeable in the model sandbox. The multiples are
// computed from the snapshot at run time, so a new snapshot re-measures them.

